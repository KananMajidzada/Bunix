#!/usr/bin/env python3
"""Turn a directory of files into a Hare table, so the kernel can serve them.

The filesystem is built at boot out of tables like this, so anything a program
is expected to find inside Bunix has to be in one. Used for the compiler's own
headers and for the example sources it compiles.

    embed.py <srcdir> <out.ha> <symbol>

writes a file holding

    export type <symbol>_file = struct { nam: str, bytes: []u8 };
    export const <symbol>s: [N]<symbol>_file = [ ... ];
"""

import os
import sys


def walk(src):
    out = []
    for root, dirs, files in os.walk(src):
        dirs.sort()
        for f in sorted(files):
            path = os.path.join(root, f)
            name = os.path.relpath(path, src).replace(os.sep, '/')
            out.append((name, path))
    out.sort()
    return out


def sym(name):
    return ''.join(c if c.isalnum() else '_' for c in name)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, out, table = sys.argv[1], sys.argv[2], sys.argv[3]

    files = walk(src)
    if not files:
        sys.exit('embed.py: no files under %s' % src)

    with open(out, 'w') as f:
        f.write('// Generated by tools/embed.py from %s. Do not edit.\n\n' % src)
        f.write('export type %s_file = struct {\n\tnam: str,\n\tbytes: []u8,\n};\n\n'
                % table)

        total = 0
        for name, path in files:
            data = open(path, 'rb').read()
            total += len(data)
            f.write('const %s: [%s]u8 = [' % (sym(name), len(data)))
            f.write(','.join(str(b) for b in data))
            f.write('];\n')

        f.write('\nexport const %ss: [%s]%s_file = [\n' % (table, len(files), table))
        for name, _ in files:
            f.write('\t%s_file { nam = "%s", bytes = %s[..] },\n'
                    % (table, name, sym(name)))
        f.write('];\n')

    print('embed.py: %s <- %d files, %d bytes' % (out, len(files), total))


if __name__ == '__main__':
    main()